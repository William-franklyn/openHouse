"""Hashing and random-code helpers.

Session tokens and device IDs are hashed with SHA-256 (they're already
high-entropy random values generated by the server/browser, so a fast
hash is fine and lets us index + look them up directly). The owner
recovery code is low-entropy enough to be guessed/brute-forced, so it
gets a slow password hash (bcrypt) instead, same as the README asks for.
"""

import hashlib
import secrets

import bcrypt


def hash_token(token: str) -> str:
    return hashlib.sha256(token.encode("utf-8")).hexdigest()


def gen_session_token() -> str:
    return secrets.token_urlsafe(32)


def hash_device_id(device_id: str) -> str:
    return hashlib.sha256(device_id.encode("utf-8")).hexdigest()


def gen_recovery_code(length: int) -> str:
    alphabet = "23456789ABCDEFGHJKMNPQRSTUVWXYZ"
    return "".join(secrets.choice(alphabet) for _ in range(length))


def hash_recovery_code(code: str) -> str:
    return bcrypt.hashpw(code.encode("utf-8"), bcrypt.gensalt()).decode("ascii")


def verify_recovery_code(code: str, hashed: str) -> bool:
    try:
        return bcrypt.checkpw(code.encode("utf-8"), hashed.encode("ascii"))
    except ValueError:
        return False


def gen_room_code(alphabet: str, length: int) -> str:
    return "".join(secrets.choice(alphabet) for _ in range(length))


def gen_invite_code() -> str:
    return secrets.token_hex(6)
